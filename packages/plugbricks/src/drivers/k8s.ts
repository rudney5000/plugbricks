import { issue } from "../issues.js";
import {
  initContainerName,
  type Plan,
  type PlanRequirement,
  type PlanRouter,
  type PlanScripts,
  type PlanService,
  type Value,
} from "../plan.js";
import { isText, PlugbricksError } from "../platform.js";
import { toYaml, toYamlDocuments, type Yaml } from "../yaml.js";
import {
  escapeDollars,
  PROVISION_MOUNT,
  ROUTER_CONFIG_DIR,
  ROUTER_CONFIG_FILE,
  ROUTER_CONTAINER_PORT,
  ROUTER_ENV,
  ROUTER_LIVE_PATH,
  ROUTER_NAME,
  ROUTER_READY_PATH,
  ROUTER_UID,
  WAIT_ARGV0,
  WAIT_SCRIPT,
} from "./common.js";

export const K8S_NAMESPACE_FILE = ".generated/k8s/namespace.yaml";
export const K8S_RESOURCES_FILE = ".generated/k8s/resources.yaml";
/** The Secret manifest holds the secret values, so it lives in .secrets/, never in .generated/. */
export const K8S_SECRET_FILE = ".secrets/k8s-secret.yaml";
export const K8S_SECRET_NAME = "plugbricks-secrets";

export const MANAGED_BY = "app.kubernetes.io/managed-by";
export const BRICK_LABEL = "plugbricks/brick";
export const SERVICE_LABEL = "plugbricks/service";
/** Marks the objects of the router, which belongs to no brick: `up` removes them when the last subgraph goes. */
export const COMPONENT_LABEL = "plugbricks/component";
/** The router configuration, beside the other generated files (the router's ConfigMap holds the same text). */
export const K8S_ROUTER_CONFIG_FILE = `.generated/k8s/${ROUTER_CONFIG_FILE}`;
/** Name of the router's ConfigMap. */
export const ROUTER_CONFIGMAP = `${ROUTER_NAME}-config`;
/** Kinds `up` deletes for removed bricks and `down` deletes for all. Never PersistentVolumeClaim, never Secret. */
export const DISPOSABLE_KINDS = "deployment,service,configmap";

/** Size a PersistentVolumeClaim requests; manifests have no size field yet. */
export const VOLUME_SIZE = "1Gi";
/** A ConfigMap holds at most 1 MiB, keys and metadata included; keep room for them. */
export const CONFIGMAP_MAX_BYTES = 1_000_000;

const HEADER = '# Generated by plugbricks from platform.lock and .platform/bricks/. Do not edit: run "plugbricks generate".\n';

function labels(plan: Plan, brick?: string): Record<string, string> {
  return {
    [MANAGED_BY]: "plugbricks",
    "app.kubernetes.io/part-of": plan.platform,
    ...(brick ? { [BRICK_LABEL]: brick } : {}),
  };
}

const routerMeta = (plan: Plan, name: string) => ({
  name,
  namespace: plan.platform,
  labels: { ...labels(plan), [COMPONENT_LABEL]: ROUTER_NAME },
});

const meta = (plan: Plan, name: string, brick?: string) => ({ name, namespace: plan.platform, labels: labels(plan, brick) });

/**
 * Container env. Each secret becomes its own variable read from the Secret, listed first; a value
 * that contains a secret refers to it as `$(PB_X)`, which Kubernetes expands because the
 * variable is defined earlier in the list. Literal `$` are doubled.
 */
function envList(values: Record<string, Value>): Yaml[] | undefined {
  const secrets = [...new Set(Object.values(values).flatMap((v) => v.flatMap((p) => (typeof p === "string" ? [] : [p.secret]))))].sort();
  const out: Yaml[] = [
    ...secrets.map((s) => ({ name: s, valueFrom: { secretKeyRef: { name: K8S_SECRET_NAME, key: s } } })),
    ...Object.keys(values).map((k) => ({
      name: k,
      value: values[k].map((p) => (typeof p === "string" ? escapeDollars(p) : `$(${p.secret})`)).join(""),
    })),
  ];
  return out.length ? out : undefined;
}

const scriptsVolume = (capability: string) => `scripts-${capability}`;

function initContainers(s: PlanService, plan: Plan): { containers: Yaml[]; volumes: Yaml[] } {
  const containers: Yaml[] = [];
  const volumes: Yaml[] = [];
  for (const cap of s.requires) {
    const r: PlanRequirement = plan.requirements.find((x) => x.consumer === s.brick && x.capability === cap)!;
    if (r.wait) {
      containers.push({
        name: initContainerName("wait", cap),
        image: r.wait.image,
        command: ["/bin/sh", "-c", escapeDollars(WAIT_SCRIPT), WAIT_ARGV0],
        args: r.wait.exec.map(escapeDollars),
        env: [
          { name: "PB_WAIT_FOR", value: `${cap} from ${r.providerService} (for ${r.consumer})` },
          { name: "PB_WAIT_INTERVAL", value: String(r.wait.intervalSeconds) },
          { name: "PB_WAIT_TIMEOUT", value: String(r.wait.timeoutSeconds) },
        ],
      });
    }
    containers.push({
      name: initContainerName("provision", cap),
      image: r.provision.image,
      command: r.provision.command.map(escapeDollars),
      env: envList(r.provision.env),
      volumeMounts: r.provision.scripts ? [{ name: scriptsVolume(cap), mountPath: PROVISION_MOUNT, readOnly: true }] : undefined,
    });
    if (r.provision.scripts) {
      const sc = plan.scripts.find((x) => x.name === r.provision.scripts)!;
      volumes.push({
        name: scriptsVolume(cap),
        // 0555, like the read-only bind mount of Compose keeps an executable script runnable.
        configMap: { name: sc.name, defaultMode: 0o555, items: configMapKeys(sc).map(({ key, path }) => ({ key, path })) },
      });
    }
  }
  return { containers, volumes };
}

/** ConfigMap keys allow only [-._a-zA-Z0-9]: each file gets a sanitized key, mounted back at its path. */
function configMapKeys(sc: PlanScripts): { key: string; path: string; data: Buffer }[] {
  const used = new Set<string>();
  return sc.files.map((f, i) => {
    let key = f.path.replace(/[^-._a-zA-Z0-9]/g, "_");
    if (used.has(key)) key = `${key}-${i}`;
    used.add(key);
    return { key, path: f.path, data: f.data };
  });
}

function configMap(sc: PlanScripts, plan: Plan): Yaml {
  const files = configMapKeys(sc);
  const size = files.reduce((n, f) => n + f.data.length + f.key.length, 0);
  if (size > CONFIGMAP_MAX_BYTES) {
    throw new PlugbricksError([
      issue("PROVISION_SCRIPTS_TOO_LARGE", "", {
        brick: sc.brick,
        capability: sc.capability,
        size: String(size),
        max: String(CONFIGMAP_MAX_BYTES),
      }),
    ]);
  }
  const text = files.filter((f) => isText(f.data));
  const binary = files.filter((f) => !isText(f.data));
  return {
    apiVersion: "v1",
    kind: "ConfigMap",
    metadata: meta(plan, sc.name, sc.brick),
    data: text.length ? Object.fromEntries(text.map((f) => [f.key, f.data.toString("utf8")])) : undefined,
    binaryData: binary.length ? Object.fromEntries(binary.map((f) => [f.key, f.data.toString("base64")])) : undefined,
  };
}

function probe(s: PlanService, startup: boolean): Yaml {
  const h = s.healthcheck!;
  return {
    exec: { command: h.exec },
    periodSeconds: h.intervalSeconds,
    timeoutSeconds: h.timeoutSeconds,
    failureThreshold: startup ? Math.ceil(h.startPeriodSeconds / h.intervalSeconds) + h.retries : h.retries,
  };
}

function deployment(s: PlanService, plan: Plan): Yaml {
  const init = initContainers(s, plan);
  const podLabels = { ...labels(plan, s.brick), [SERVICE_LABEL]: s.name };
  const volumes = [...s.volumes.map((v) => ({ name: v.volume, persistentVolumeClaim: { claimName: v.volume } })), ...init.volumes];
  return {
    apiVersion: "apps/v1",
    kind: "Deployment",
    metadata: meta(plan, s.name, s.brick),
    spec: {
      replicas: 1,
      // Two pods must never mount the same ReadWriteOnce volume during a rollout.
      strategy: s.volumes.length ? { type: "Recreate" } : undefined,
      selector: { matchLabels: { [SERVICE_LABEL]: s.name } },
      template: {
        metadata: { labels: podLabels },
        spec: {
          initContainers: init.containers.length ? init.containers : undefined,
          containers: [
            {
              name: s.service,
              image: s.image,
              ports: [{ containerPort: s.port }, ...s.extraPorts.map((p) => ({ containerPort: p.port }))],
              env: envList(s.env),
              // Readiness only, never liveness: a slow dependency must not get the pod killed.
              readinessProbe: s.healthcheck ? probe(s, false) : undefined,
              startupProbe: s.healthcheck && s.healthcheck.startPeriodSeconds > 0 ? probe(s, true) : undefined,
              volumeMounts: s.volumes.length ? s.volumes.map((v) => ({ name: v.volume, mountPath: v.mountPath })) : undefined,
            },
          ],
          volumes: volumes.length ? volumes : undefined,
        },
      },
    },
  };
}

/**
 * The router's ConfigMap, Service and Deployment. A ClusterIP Service only: nothing is exposed outside the
 * cluster (no Ingress, no NodePort, no LoadBalancer). Probes are HTTP, since the image has no shell. It runs
 * as a non-root user with a read-only root filesystem, no capability and no privilege escalation.
 */
function routerDocs(r: PlanRouter, plan: Plan): Yaml[] {
  const size = Buffer.byteLength(r.config) + ROUTER_CONFIG_FILE.length;
  if (size > CONFIGMAP_MAX_BYTES) {
    throw new PlugbricksError([issue("ROUTER_CONFIG_TOO_LARGE", "", { size: String(size), max: String(CONFIGMAP_MAX_BYTES) })]);
  }
  const podLabels = { ...routerMeta(plan, r.name).labels, [SERVICE_LABEL]: r.name };
  return [
    { apiVersion: "v1", kind: "ConfigMap", metadata: routerMeta(plan, ROUTER_CONFIGMAP), data: { [ROUTER_CONFIG_FILE]: r.config } },
    {
      apiVersion: "v1",
      kind: "Service",
      metadata: routerMeta(plan, r.name),
      spec: {
        type: "ClusterIP",
        selector: { [SERVICE_LABEL]: r.name },
        ports: [{ name: "graphql", port: r.port, targetPort: ROUTER_CONTAINER_PORT }],
      },
    },
    {
      apiVersion: "apps/v1",
      kind: "Deployment",
      metadata: routerMeta(plan, r.name),
      spec: {
        replicas: 1,
        selector: { matchLabels: { [SERVICE_LABEL]: r.name } },
        template: {
          // The router reads its configuration once, at start; a changed hash restarts the pod.
          metadata: { labels: podLabels, annotations: { "plugbricks/router-config-sha256": r.configSha256 } },
          spec: {
            securityContext: { seccompProfile: { type: "RuntimeDefault" } },
            containers: [
              {
                name: r.name,
                image: r.image,
                ports: [{ name: "graphql", containerPort: ROUTER_CONTAINER_PORT }],
                env: Object.entries(ROUTER_ENV).map(([name, value]) => ({ name, value })),
                readinessProbe: {
                  httpGet: { path: ROUTER_READY_PATH, port: ROUTER_CONTAINER_PORT },
                  periodSeconds: 5,
                  timeoutSeconds: 2,
                  failureThreshold: 6,
                },
                livenessProbe: {
                  httpGet: { path: ROUTER_LIVE_PATH, port: ROUTER_CONTAINER_PORT },
                  periodSeconds: 10,
                  timeoutSeconds: 2,
                  failureThreshold: 6,
                },
                securityContext: {
                  runAsNonRoot: true,
                  runAsUser: ROUTER_UID,
                  runAsGroup: ROUTER_UID,
                  readOnlyRootFilesystem: true,
                  allowPrivilegeEscalation: false,
                  capabilities: { drop: ["ALL"] },
                },
                volumeMounts: [{ name: "config", mountPath: ROUTER_CONFIG_DIR, readOnly: true }],
              },
            ],
            volumes: [{ name: "config", configMap: { name: ROUTER_CONFIGMAP, defaultMode: 0o444 } }],
          },
        },
      },
    },
  ];
}

/**
 * plan -> Kubernetes manifests, in the namespace named after the platform. One Deployment and
 * one Service per service; before a consumer's container starts, its init containers wait for
 * each required capability (wait: healthy) and run the provision task. Volumes are
 * PersistentVolumeClaims, which no command but `up --prune-volumes` deletes.
 */
export function renderK8s(plan: Plan): Record<string, string> {
  const namespace: Yaml = { apiVersion: "v1", kind: "Namespace", metadata: { name: plan.platform, labels: labels(plan) } };
  const docs: Yaml[] = [
    ...plan.scripts.map((sc) => configMap(sc, plan)),
    ...plan.volumes.map((v) => ({
      apiVersion: "v1",
      kind: "PersistentVolumeClaim",
      metadata: meta(plan, v.name, v.brick),
      spec: { accessModes: ["ReadWriteOnce"], resources: { requests: { storage: VOLUME_SIZE } } },
    })),
    ...plan.services.map((s) => ({
      apiVersion: "v1",
      kind: "Service",
      metadata: meta(plan, s.name, s.brick),
      spec: {
        selector: { [SERVICE_LABEL]: s.name },
        ports: [
          { name: "main", port: s.port, targetPort: s.port },
          ...s.extraPorts.map((p) => ({ name: p.name, port: p.port, targetPort: p.port })),
        ],
      },
    })),
    ...plan.services.map((s) => deployment(s, plan)),
    ...(plan.router ? routerDocs(plan.router, plan) : []),
  ];
  return {
    [K8S_NAMESPACE_FILE]: HEADER + toYaml(namespace),
    [K8S_RESOURCES_FILE]: HEADER + (docs.length ? toYamlDocuments(docs) : "# No brick installed.\n"),
    ...(plan.router ? { [K8S_ROUTER_CONFIG_FILE]: plan.router.config } : {}),
  };
}

/** The Secret with every secret the plan uses. Written to .secrets/, never to .generated/. */
export function renderK8sSecret(plan: Plan, values: Map<string, string>): string {
  return (
    "# Generated by plugbricks. Holds secret values: never commit or share this file.\n" +
    toYaml({
      apiVersion: "v1",
      kind: "Secret",
      metadata: meta(plan, K8S_SECRET_NAME),
      type: "Opaque",
      stringData: Object.fromEntries(plan.secrets.map((s) => [s.env, values.get(s.env)!])),
    })
  );
}
