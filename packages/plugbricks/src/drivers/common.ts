import type { Plan, PlanService, Value } from "../plan.js";

/**
 * Shell script run by every wait task (Compose) and wait init container (Kubernetes). It runs the
 * provider's ready command, without a shell, until it succeeds or PB_WAIT_TIMEOUT seconds have
 * passed; on timeout it exits 124, which the drivers report as WAIT_TIMEOUT. The command comes
 * as positional parameters, so it is never re-parsed. Needs /bin/sh, date and sleep in the image.
 */
export const WAIT_SCRIPT = [
  "deadline=$(( $(date +%s) + PB_WAIT_TIMEOUT ))",
  'until "$@" >/dev/null 2>&1; do',
  '  if [ "$(date +%s)" -ge "$deadline" ]; then',
  '    echo "plugbricks: WAIT_TIMEOUT: gave up waiting for $PB_WAIT_FOR after ${PB_WAIT_TIMEOUT}s" >&2',
  "    exit 124",
  "  fi",
  '  sleep "$PB_WAIT_INTERVAL"',
  "done",
  'echo "plugbricks: $PB_WAIT_FOR is ready"',
].join("\n");

/** Exit code of the wait script when it gives up. */
export const WAIT_TIMEOUT_EXIT = 124;

/** $0 of the wait script: shows in process lists and error messages. */
export const WAIT_ARGV0 = "plugbricks-wait";

/** Where provision scripts are mounted in the provision container. */
export const PROVISION_MOUNT = "/provision";

/**
 * Both Docker Compose (variable interpolation) and Kubernetes (`$(VAR)` expansion in command,
 * args and env) read `$$` as one literal `$`. Doubling every `$` keeps literal text literal.
 */
export const escapeDollars = (s: string) => s.replace(/\$/g, "$$$$");

// ---------- the Cosmo router ----------
// The router is rendered by plugbricks itself and is not a brick (decision D9): its image has no shell
// and no wget, so it cannot carry the exec probes a manifest declares, and it must never be published
// anywhere but on the loopback address. Everything below was checked by running this image.

/** Runtime name of the router: Compose service, Kubernetes Deployment, Service and container. */
export const ROUTER_NAME = "router";

/**
 * The Cosmo router image, the multi-architecture index pinned by digest. tools.json (images.router) holds
 * the same reference; a test keeps the two equal, and the pinning rule accepts it.
 */
export const ROUTER_IMAGE =
  "ghcr.io/wundergraph/cosmo/router:0.372.0@sha256:bfe6d89a89ab70975bc874dc234600fe5a6ba6d9498485465a31be4c5b9d0205";

/** Port the router listens on inside its container. */
export const ROUTER_CONTAINER_PORT = 3002;

/** The execution configuration generated by plugbricks, beside compose.yaml and in the router's ConfigMap. */
export const ROUTER_CONFIG_FILE = "router-config.json";
export const ROUTER_CONFIG_DIR = "/config";
export const ROUTER_CONFIG_PATH = `${ROUTER_CONFIG_DIR}/${ROUTER_CONFIG_FILE}`;

/** Uid and gid the router runs as: non-root, and the router starts and serves with a read-only root filesystem. */
export const ROUTER_UID = 65532;

/**
 * Environment of the router, each variable checked against router 0.372.0:
 * - LISTEN_ADDR, EXECUTION_CONFIG_FILE_PATH: where it listens and the static configuration to serve;
 * - PLAYGROUND_ENABLED=false: no GraphQL playground on "/" (the variable still works but the router logs
 *   that it is deprecated in favour of the playground.enabled option of its YAML config);
 * - TRACING_ENABLED, METRICS_OTLP_ENABLED, PROMETHEUS_ENABLED = false: no OpenTelemetry export and no
 *   Prometheus listener;
 * - COSMO_TELEMETRY_DISABLED=true and DO_NOT_TRACK=1: without them the router opens an HTTPS connection to
 *   eu.i.posthog.com at start (anonymous usage tracking, even with no graph token); with them, no DNS query
 *   and no outgoing connection in 25 s.
 * - CORS_ALLOW_ORIGINS (added by routerEnv): without it the router allows every origin, and a cross-site
 *   POST with content-type text/plain ran a mutation; with it, any other Origin gets 403 and its request
 *   is not run (D17).
 */
const ROUTER_ENV: Record<string, string> = {
  COSMO_TELEMETRY_DISABLED: "true",
  DO_NOT_TRACK: "1",
  EXECUTION_CONFIG_FILE_PATH: ROUTER_CONFIG_PATH,
  LISTEN_ADDR: `0.0.0.0:${ROUTER_CONTAINER_PORT}`,
  METRICS_OTLP_ENABLED: "false",
  PLAYGROUND_ENABLED: "false",
  PROMETHEUS_ENABLED: "false",
  TRACING_ENABLED: "false",
};

/** The router's environment, sorted by name: the fixed variables above and the origins it accepts. */
export function routerEnv(allowedOrigins: string[]): Record<string, string> {
  const env = { ...ROUTER_ENV, CORS_ALLOW_ORIGINS: allowedOrigins.join(",") };
  return Object.fromEntries(Object.entries(env).sort(([a], [b]) => a.localeCompare(b)));
}

/** Probes of the router (it has no shell, so no exec probe): its own health endpoints. */
export const ROUTER_READY_PATH = "/health/ready";
export const ROUTER_LIVE_PATH = "/health/live";

/**
 * The environment of a service, plus what a web brick's service is given when the platform has a router
 * (D17): GRAPHQL_URL, the router as the platform reaches it (`internalGraphql`, which differs per runtime),
 * and PUBLIC_GRAPHQL_URL, the router as a browser on this machine reaches it. Sorted by name.
 */
export function serviceEnv(s: PlanService, plan: Plan, internalGraphql: string): Record<string, Value> {
  if (!s.web || !plan.router) return s.env;
  const env: Record<string, Value> = {
    ...s.env,
    GRAPHQL_URL: [internalGraphql],
    PUBLIC_GRAPHQL_URL: [`http://127.0.0.1:${plan.router.port}/graphql`],
  };
  return Object.fromEntries(Object.entries(env).sort(([a], [b]) => a.localeCompare(b)));
}
