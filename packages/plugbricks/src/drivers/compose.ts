import type { Plan, PlanRequirement, PlanService, Value } from "../plan.js";
import { toYaml, type Yaml } from "../yaml.js";
import { escapeDollars, PROVISION_MOUNT, WAIT_ARGV0, WAIT_SCRIPT } from "./common.js";

/** Generated Compose file, relative to the platform root. */
export const COMPOSE_FILE = ".generated/compose/compose.yaml";

/**
 * Docker volume name of a runtime volume. Set explicitly in the Compose file (it is also
 * Compose's default, `<project>_<key>`), so `up --prune-volumes` deletes exactly that name.
 */
export const composeVolumeName = (platform: string, volume: string) => `${platform}_${volume}`;

/**
 * Literal text has every `$` doubled; a secret becomes `${PB_X:?…}`, read from
 * .secrets/secrets.env through --env-file. Compose refuses to start when the variable is missing
 * instead of starting with an empty password.
 */
function env(value: Value): string {
  return value
    .map((p) => (typeof p === "string" ? escapeDollars(p) : `\${${p.secret}:?missing secret; run plugbricks generate}`))
    .join("");
}

function envMap(values: Record<string, Value>): Record<string, string> | undefined {
  const keys = Object.keys(values);
  return keys.length ? Object.fromEntries(keys.map((k) => [k, env(values[k])])) : undefined;
}

const seconds = (n: number) => `${n}s`;

function service(s: PlanService, plan: Plan): Yaml {
  const reqs = s.requires.map((cap) => plan.requirements.find((r) => r.consumer === s.brick && r.capability === cap)!);
  return {
    image: s.image,
    environment: envMap(s.env),
    healthcheck: s.healthcheck && {
      test: ["CMD", ...s.healthcheck.exec.map(escapeDollars)],
      interval: seconds(s.healthcheck.intervalSeconds),
      timeout: seconds(s.healthcheck.timeoutSeconds),
      retries: s.healthcheck.retries,
      start_period: seconds(s.healthcheck.startPeriodSeconds),
    },
    volumes: s.volumes.length ? s.volumes.map((v) => ({ type: "volume", source: v.volume, target: v.mountPath })) : undefined,
    depends_on: reqs.length
      ? Object.fromEntries(reqs.map((r) => [r.provision.name, { condition: "service_completed_successfully" }]))
      : undefined,
    restart: "unless-stopped",
  };
}

function waitTask(r: PlanRequirement): Yaml {
  const w = r.wait!;
  return {
    image: w.image,
    entrypoint: ["/bin/sh", "-c", escapeDollars(WAIT_SCRIPT), WAIT_ARGV0],
    command: w.exec.map(escapeDollars),
    environment: {
      PB_WAIT_FOR: `${r.capability} from ${r.providerService} (for ${r.consumer})`,
      PB_WAIT_INTERVAL: String(w.intervalSeconds),
      PB_WAIT_TIMEOUT: String(w.timeoutSeconds),
    },
    depends_on: { [r.providerService]: { condition: "service_started" } },
    restart: "no",
  };
}

function provisionTask(r: PlanRequirement, plan: Plan): Yaml {
  const scripts = r.provision.scripts && plan.scripts.find((s) => s.name === r.provision.scripts)!;
  return {
    image: r.provision.image,
    // Overrides the image entrypoint, and with it the image's default command: exactly the manifest's argv runs.
    entrypoint: r.provision.command.map(escapeDollars),
    environment: envMap(r.provision.env),
    // Relative to this file's folder (.generated/compose/), so the file is the same on every machine.
    volumes: scripts ? [{ type: "bind", source: `../../${scripts.hostPath}`, target: PROVISION_MOUNT, read_only: true }] : undefined,
    depends_on: r.wait
      ? { [r.wait.name]: { condition: "service_completed_successfully" } }
      : { [r.providerService]: { condition: "service_started" } },
    restart: "no",
  };
}

/**
 * plan -> compose.yaml. The project name is the platform name. Nothing is published on the
 * host. Order of start: provider, then for each consumer and capability the wait task (wait:
 * healthy), then the provision task, then the consumer's services.
 */
export function renderCompose(plan: Plan): Record<string, string> {
  const services: Record<string, Yaml> = {};
  const entries: [string, Yaml][] = [
    ...plan.services.map((s) => [s.name, service(s, plan)] as [string, Yaml]),
    ...plan.requirements.flatMap((r) => [
      ...(r.wait ? [[r.wait.name, waitTask(r)] as [string, Yaml]] : []),
      [r.provision.name, provisionTask(r, plan)] as [string, Yaml],
    ]),
  ];
  for (const [name, def] of entries.sort(([a], [b]) => a.localeCompare(b))) services[name] = def;
  const doc: Yaml = {
    name: plan.platform,
    services,
    volumes: plan.volumes.length
      ? Object.fromEntries(plan.volumes.map((v) => [v.name, { name: composeVolumeName(plan.platform, v.name) }]))
      : undefined,
  };
  return {
    [COMPOSE_FILE]: `# Generated by plugbricks from platform.lock and .platform/bricks/. Do not edit: run "plugbricks generate".\n${toYaml(doc)}`,
  };
}
