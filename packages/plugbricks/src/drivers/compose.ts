import type { Plan, PlanRequirement, PlanRouter, PlanService, Value } from "../plan.js";
import { toYaml, type Yaml } from "../yaml.js";
import {
  escapeDollars,
  PROVISION_MOUNT,
  ROUTER_AUTH_FILE,
  ROUTER_AUTH_PATH,
  ROUTER_CONFIG_FILE,
  ROUTER_CONFIG_PATH,
  ROUTER_CONTAINER_PORT,
  routerEnv,
  serviceEnv,
  ROUTER_NAME,
  ROUTER_UID,
  WAIT_ARGV0,
  WAIT_SCRIPT,
} from "./common.js";

/** Generated Compose file, relative to the platform root. */
export const COMPOSE_FILE = ".generated/compose/compose.yaml";

/** The router configuration, beside compose.yaml (the router service mounts it from there). */
export const COMPOSE_ROUTER_CONFIG = `.generated/compose/${ROUTER_CONFIG_FILE}`;

/**
 * Docker volume name of a runtime volume. Set explicitly in the Compose file (it is also
 * Compose's default, `<project>_<key>`), so `up --prune-volumes` deletes exactly that name.
 */
export const composeVolumeName = (platform: string, volume: string) => `${platform}_${volume}`;

/**
 * Literal text has every `$` doubled; a secret becomes `${PB_X:?…}`, read from
 * .secrets/secrets.env through --env-file. Compose refuses to start when the variable is missing
 * instead of starting with an empty password.
 */
function env(value: Value, o: RenderOptions): string {
  const missing = o.exported ? "missing secret; copy .env.example to .env and fill it" : "missing secret; run plugbricks generate";
  return value.map((p) => (typeof p === "string" ? escapeDollars(p) : `\${${p.secret}:?${missing}}`)).join("");
}

function envMap(values: Record<string, Value>, o: RenderOptions): Record<string, string> | undefined {
  const keys = Object.keys(values);
  return keys.length ? Object.fromEntries(keys.map((k) => [k, env(values[k], o)])) : undefined;
}

/**
 * `exported` (D34): the files leave the project, to be used without plugbricks. The provision scripts are read from a
 * `scripts/<name>/` folder beside the file, and the header and the message of a missing secret do not name plugbricks
 * commands that the copy's reader does not have.
 */
export interface RenderOptions {
  exported?: boolean;
}

/** Where an exported Compose file finds the provision scripts of a capability, relative to itself. */
export const exportedScriptsDir = (scriptsName: string) => `scripts/${scriptsName}`;

const HEADER = '# Generated by plugbricks from platform.lock and .platform/bricks/. Do not edit: run "plugbricks generate".\n';
export const EXPORTED_HEADER =
  "# Exported by plugbricks (D34). This copy is yours: edit it freely, plugbricks does not read it and never rewrites it.\n";

const seconds = (n: number) => `${n}s`;

function service(s: PlanService, plan: Plan, o: RenderOptions): Yaml {
  const reqs = s.requires.map((cap) => plan.requirements.find((r) => r.consumer === s.brick && r.capability === cap)!);
  return {
    image: s.image,
    environment: envMap(serviceEnv(s, plan, `http://${ROUTER_NAME}:${ROUTER_CONTAINER_PORT}/graphql`), o),
    healthcheck: s.healthcheck && {
      test: ["CMD", ...s.healthcheck.exec.map(escapeDollars)],
      interval: seconds(s.healthcheck.intervalSeconds),
      timeout: seconds(s.healthcheck.timeoutSeconds),
      retries: s.healthcheck.retries,
      start_period: seconds(s.healthcheck.startPeriodSeconds),
    },
    volumes: s.volumes.length ? s.volumes.map((v) => ({ type: "volume", source: v.volume, target: v.mountPath })) : undefined,
    depends_on: reqs.length
      ? Object.fromEntries(reqs.map((r) => [r.provision.name, { condition: "service_completed_successfully" }]))
      : undefined,
    // A web brick's pages (D17): published like the router, on the loopback address only.
    ports: s.web ? [{ target: s.port, published: String(s.web.port), host_ip: "127.0.0.1", protocol: "tcp" }] : undefined,
    restart: "unless-stopped",
  };
}

function waitTask(r: PlanRequirement): Yaml {
  const w = r.wait!;
  return {
    image: w.image,
    entrypoint: ["/bin/sh", "-c", escapeDollars(WAIT_SCRIPT), WAIT_ARGV0],
    command: w.exec.map(escapeDollars),
    environment: {
      PB_WAIT_FOR: `${r.capability} from ${r.providerService} (for ${r.consumer})`,
      PB_WAIT_INTERVAL: String(w.intervalSeconds),
      PB_WAIT_TIMEOUT: String(w.timeoutSeconds),
    },
    depends_on: { [r.providerService]: { condition: "service_started" } },
    restart: "no",
  };
}

function provisionTask(r: PlanRequirement, plan: Plan, o: RenderOptions): Yaml {
  const scripts = r.provision.scripts && plan.scripts.find((s) => s.name === r.provision.scripts)!;
  return {
    image: r.provision.image,
    // Overrides the image entrypoint, and with it the image's default command: exactly the manifest's argv runs.
    entrypoint: r.provision.command.map(escapeDollars),
    environment: envMap(r.provision.env, o),
    // Relative to this file's folder (.generated/compose/), so the file is the same on every machine; an exported file
    // (D34) reads a copy of the scripts that sits beside it.
    volumes: scripts
      ? [
          {
            type: "bind",
            source: o.exported ? `./${exportedScriptsDir(scripts.name)}` : `../../${scripts.hostPath}`,
            target: PROVISION_MOUNT,
            read_only: true,
          },
        ]
      : undefined,
    depends_on: r.wait
      ? { [r.wait.name]: { condition: "service_completed_successfully" } }
      : { [r.providerService]: { condition: "service_started" } },
    restart: "no",
  };
}

/**
 * The router: the only service published on the host, and only on the loopback address. Its image has
 * no shell and no wget, so it has no healthcheck; it starts after every subgraph service is healthy
 * (or started, for a service that declares no healthcheck, which Compose cannot wait on). It runs as
 * a non-root user with a read-only root filesystem and no capability. No `no-new-privileges`: with
 * Docker installed as a snap, that option alone makes the exec of /router fail ("operation not
 * permitted") and the router restart forever (D9).
 */
const dependsOn = (entries: [string, Yaml][]): Record<string, Yaml> => (entries.length ? { depends_on: Object.fromEntries(entries) } : {});

function routerService(r: PlanRouter): Yaml {
  return {
    image: r.image,
    user: `${ROUTER_UID}:${ROUTER_UID}`,
    read_only: true,
    cap_drop: ["ALL"],
    environment: routerEnv(r.allowedOrigins, r.auth !== undefined),
    // The router reads its configuration once, at start; a changed hash makes Compose recreate the container.
    labels: {
      "plugbricks.router-config-sha256": r.configSha256,
      ...(r.auth ? { "plugbricks.router-auth-sha256": r.auth.yamlSha256 } : {}),
    },
    // Relative to this file's folder (.generated/compose/), like the provision scripts.
    volumes: [
      { type: "bind", source: `./${ROUTER_CONFIG_FILE}`, target: ROUTER_CONFIG_PATH, read_only: true },
      ...(r.auth ? [{ type: "bind", source: `./${ROUTER_AUTH_FILE}`, target: ROUTER_AUTH_PATH, read_only: true }] : []),
    ],
    ports: [{ target: ROUTER_CONTAINER_PORT, published: String(r.port), host_ip: "127.0.0.1", protocol: "tcp" }],
    // With a token check (D19) it also waits for the oidc provider: it cannot start without its keys. An external
    // subgraph (D33) is neither started nor waited for: a router with only those waits for nothing.
    ...dependsOn([
      ...r.subgraphs.map((s): [string, Yaml] => [s.service, { condition: s.healthy ? "service_healthy" : "service_started" }]),
      ...(r.auth ? [[r.auth.service, { condition: r.auth.healthy ? "service_healthy" : "service_started" }] as [string, Yaml]] : []),
    ]),
    // A subgraph of this machine (D33): Docker Desktop knows host.docker.internal, a Linux engine needs it given.
    ...(r.hostGateway ? { extra_hosts: ["host.docker.internal:host-gateway"] } : {}),
    restart: "unless-stopped",
  };
}

/**
 * plan -> compose.yaml. The project name is the platform name. Nothing is published on the
 * host but the router, on 127.0.0.1 (none while no brick serves a subgraph). Order of start: provider, then for each consumer and capability the wait task (wait:
 * healthy), then the provision task, then the consumer's services.
 */
export function renderCompose(plan: Plan, o: RenderOptions = {}): Record<string, string> {
  const services: Record<string, Yaml> = {};
  const entries: [string, Yaml][] = [
    ...plan.services.map((s) => [s.name, service(s, plan, o)] as [string, Yaml]),
    ...plan.requirements.flatMap((r) => [
      ...(r.wait ? [[r.wait.name, waitTask(r)] as [string, Yaml]] : []),
      [r.provision.name, provisionTask(r, plan, o)] as [string, Yaml],
    ]),
    ...(plan.router ? [[ROUTER_NAME, routerService(plan.router)] as [string, Yaml]] : []),
  ];
  for (const [name, def] of entries.sort(([a], [b]) => a.localeCompare(b))) services[name] = def;
  const doc: Yaml = {
    name: plan.platform,
    services,
    volumes: plan.volumes.length
      ? Object.fromEntries(plan.volumes.map((v) => [v.name, { name: composeVolumeName(plan.platform, v.name) }]))
      : undefined,
  };
  return {
    [COMPOSE_FILE]: `${o.exported ? EXPORTED_HEADER : HEADER}${toYaml(doc)}`,
    ...(plan.router ? { [COMPOSE_ROUTER_CONFIG]: plan.router.config } : {}),
    ...(plan.router?.auth ? { [`.generated/compose/${ROUTER_AUTH_FILE}`]: plan.router.auth.yaml } : {}),
  };
}
